#ifndef MULTIAPP_MULTIAPP_H_
#define MULTIAPP_MULTIAPP_H_

#include <stddef.h>
#include <stdint.h>

#include <zephyr/kernel.h>
#include <zephyr/shell/shell.h>

/* Bumped on incompatible changes below; the host refuses other values. */
#define MULTIAPP_ABI 1U

/* USB classes the host registers for an app, besides the CDC-ACM shell and DFU. */
#define MULTIAPP_USB_NCM    (1U << 0)
#define MULTIAPP_USB_VENDOR (1U << 1)
/*
 * The host's own: the FAT volume as a USB drive, which the PC may use while the app runs
 * (src/drive.c). src/profile.h adds it to every app that leaves an IN endpoint free, so an app's
 * `USB` mask does not name it, and boots without an app have it alone.
 */
#define MULTIAPP_USB_MSC    (1U << 2)
/*
 * With MULTIAPP_USB_MSC: the app registers the drive's disks itself (MicroPython's
 * src/usb_disks.c) and the host's proxy stays out of it.
 */
#define MULTIAPP_USB_OWN_DISKS (1U << 3)

/* What ends an extension file (apptrail.py), checked before llext reads it. */
struct multiapp_trailer {
	uint32_t magic;
	/* The ELF in front of the trailer, and its CRC-32 (crc32_ieee()). */
	uint32_t elf_size;
	uint32_t crc32;
	/* Stack of the thread that runs the app's main(). */
	uint32_t stack_size;
	uint8_t build_id[16];
};

#define MULTIAPP_TRAILER_MAGIC 0x3150414DU /* "MAP1" */

/*
 * A hot-swap kernel's file (multiapp_kernel(), include/multiapp/stage.h) has the same trailer with
 * this magic, so that neither kind loads as the other; its stack_size is the placement, a value of
 * enum multiapp_place (src/apps.h): the kernel's code and data in PSRAM or in internal RAM.
 */
#define MULTIAPP_KTRAILER_MAGIC 0x31544B4DU /* "MKT1" */

/*
 * What an extension may define, found by name when the host unloads it (doc/apps/multiapp-internals.md):
 *
 * - int multiapp_module_up(void): a module, once its constructors have run.
 * - int multiapp_module_down(void): the inverse. It stops what the module started and returns what
 *   it took from the host (interrupts, threads, interface, claims), or fails with a negative errno
 *   and leaves the module loaded (the host then reboots into the next app instead).
 * - int multiapp_app_stop(void): an app; asks main() and the app's own threads to end. The host
 *   joins main()'s thread after it. Without it, only an app whose main() returns can be replaced
 *   in place.
 */

/* Every extension exports one as "multiapp_info" (generated by CMakeLists.txt). */
struct multiapp_info {
	uint32_t abi;
	const char *name;
	/* The app's own main(), as in its standalone build. */
	int (*main)(void);
};

/*
 * An object the host defines for an extension (include/multiapp/ext.h): the
 * extension leaves one in its .multiapp_host section, exports.py reads it and
 * generates the definition, exported under @a name.
 */
struct multiapp_host_object {
	char name[56];
	uint32_t kind;
	uint32_t arg[3];
};

/* A fixed net_buf pool: arg = count, data size, user data size. */
#define MULTIAPP_HOST_POOL 1U
/* Internal RAM in the area (ESP_SDR_HIGH_BUF_DEFINE()): arg = size, alignment. */
#define MULTIAPP_HOST_AREA 2U
/* A buffer in PSRAM (ESP_SDR_PSRAM_BUF_DEFINE()): arg = size, alignment. */
#define MULTIAPP_HOST_PSRAM 3U

/* A module's devices and SYS_INIT entries (ext/module_devices.c), which the host runs. */
struct init_entry;

struct multiapp_init_table {
	const struct init_entry *start;
	const struct init_entry *end;
};

/*
 * Hand the host's Wi-Fi interface to @p dev, the wifi module's device (src/wifi_netif.c), and bring
 * it up. 0 or a negative errno.
 */
int multiapp_wifi_bind(const struct device *dev);

/*
 * Undo multiapp_wifi_bind() after the module's driver has shut down: the interface goes down, its
 * IPv4 addresses go, and it is on the host's idle device again.
 */
int multiapp_wifi_unbind(const struct device *dev);

/*
 * The device's claim on the FAT volume (src/drive.c; see "Writers and readers of the volume" in
 * doc/apps/multiapp-internals.md). The PC may have the volume as a USB drive; code of the host or
 * an extension that reads it calls multiapp_drive_read_begin() before and multiapp_drive_read_end()
 * after, code that writes it multiapp_drive_write_begin() and multiapp_drive_write_end(), from the
 * same thread. Both take the one lock that orders the device's users, wait for the PC's disk access
 * in flight to end (100 ms with none running) and then let the device mount the volume itself
 * (fs_mount(): the volume is read afresh), as nothing mounts it between claims.
 *
 * - A reader does not hide the drive: the PC's next accesses wait until the end of the claim and go
 *   on. A file the PC is still copying is half there: check what was read and ask again.
 * - A writer hides the drive (the PC sees no medium and drops what it cached), and at the end
 *   syncs the volume and keeps the drive away at least 3 s from when it went, and while a ring runs
 *   until it stops, so that the PC reads the volume again. Not for a thread that streams: keep it
 *   short.
 *
 * Calls nest in one thread (a write inside a read is refused). Return 0; -EAGAIN if another user
 * kept the lock for @p timeout; -EBUSY if the PC's access did not end in that time (go without the
 * volume, it was not taken); -EDEADLK from the USB thread, which carries the PC's data and so
 * cannot wait for it, and for a write inside a read. Without the drive on the bus (a boot without
 * the class) it is only the lock. The caller's stack must be internal RAM: the flash driver turns
 * the cache off.
 */
int multiapp_drive_read_begin(k_timeout_t timeout);
void multiapp_drive_read_end(void);
int multiapp_drive_write_begin(k_timeout_t timeout);
void multiapp_drive_write_end(void);

/*
 * The radio module's tell whether a ring runs, from multiapp_module_up() until multiapp_module_down()
 * takes it back with NULL (after which no call of it is running): a writer's hold is not over
 * while it returns true.
 */
void multiapp_drive_busy_hook(bool (*busy)(void));

/*
 * An app that streams (stream_eth, a network transmit) calls hold when it starts and release when
 * it ends: while any hold is open, MCUmgr refuses image uploads (src/netsvc.c; the flash write
 * stops the cache). osmosdr needs none: the host sees its ring run (multiapp_ring_running()).
 */
void multiapp_stream_hold(void);
void multiapp_stream_release(void);

/* Whether the boot's app has dump bank 2 as a module heap (BANK2): the SDR must stay off it. */
bool multiapp_bank2_reserved(void);

/*
 * For an app that wants all the PSRAM it can get: what nothing in this boot uses once the app runs,
 * from the end of what the linker placed to the top, with the shared heap only the wifi module
 * allocates from (so not in a boot that has it) and the buffer that held the app's file. Returns
 * the start and sets @p size.
 */
void *multiapp_psram_spare(size_t *size);

/*
 * Run a command of the host's Zephyr shell for a caller inside the host (an extension: MicroPython's esdr.shell()). The
 * output, with the shell's line ends (CR LF), goes to @p out in pieces. The command runs on the calling thread, which
 * must therefore be one that may touch the flash (an internal stack). 0 or the shell's negative errno; -EBUSY when
 * an SSH session has the shell for longer than a few seconds. Not while a stream runs: the caller checks.
 */
typedef void (*multiapp_shell_out_fn)(const void *data, size_t len, void *ctx);
int multiapp_shell_exec(const char *cmd, multiapp_shell_out_fn out, void *ctx);

/*
 * Make @p root, a root command of the loaded app, reachable from the host's
 * shell. An extension's SHELL_CMD_REGISTER() calls this from a constructor.
 */
void multiapp_shell_register(const struct shell_static_entry *root);

/* Take @p root off again: an extension's destructor, as it unloads. */
void multiapp_shell_unregister(const struct shell_static_entry *root);

#endif /* MULTIAPP_MULTIAPP_H_ */
