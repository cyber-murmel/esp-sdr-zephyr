"""Write the public half of an ED25519 PEM key as a C header: what the host checks extensions against.

    pubkey.py <key.pem> <out.h>

Only the public key is written (it is compiled into MCUboot as well); the private key is not printed.
"""

import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ed25519


def public_raw(key_file):
    with open(key_file, "rb") as f:
        key = serialization.load_pem_private_key(f.read(), password=None)
    if not isinstance(key, ed25519.Ed25519PrivateKey):
        sys.exit(f"pubkey.py: {key_file}: not an ED25519 key")
    return key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    raw = public_raw(sys.argv[1])
    body = ", ".join(f"0x{b:02x}" for b in raw)
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by pubkey.py: the public key extensions are signed with. */\n"
                f"static const uint8_t multiapp_ext_pubkey[32] = {{{body}}};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
