#ifndef MULTIAPP_APPS_H_
#define MULTIAPP_APPS_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <sys/types.h>

#include <zephyr/device.h>

/* Where an extension's code and data go; its symbol tables stay in PSRAM. */
enum multiapp_place {
	MULTIAPP_PLACE_PSRAM,
	/* Its IRAM_ATTR code, data and bss below bank 0, the rest in PSRAM (ext/module_fast.ld). */
	MULTIAPP_PLACE_INTERNAL,
	/* As MULTIAPP_PLACE_INTERNAL, its bss in the high region. */
	MULTIAPP_PLACE_INTERNAL_HIGH_BSS,
};

/* An extension built with this image (embedded.c, generated by CMakeLists.txt). */
struct multiapp_embedded {
	const char *name;
	/* Its file (the ELF and its trailer), NULL without CONFIG_MULTIAPP_EMBEDDED. */
	const uint8_t *elf;
	size_t size;
	/* MULTIAPP_USB_*: the USB classes it needs. */
	uint32_t usb;
	/* Whether it has buffers in multiapp_area, which it then owns for the boot. */
	bool area;
	/* A module: code other extensions call, loaded before them, no main(). */
	bool module;
	/* Where its code and data go. */
	enum multiapp_place place;
	/* A module with devices: the host runs its init table as it loads it. */
	bool devices;
	/* It takes the CDC-ACM port from the shell, and its main() starts with USB up. */
	bool console;
	/* SRAM dump bank 2 is the boot's second module heap, and the SDR leaves it alone. */
	bool bank2;
	/* The modules to load before it, NULL-terminated. */
	const char *const *requires;
};

extern const struct multiapp_embedded multiapp_embedded[];
extern const size_t multiapp_embedded_count;

const struct multiapp_embedded *multiapp_embedded_find(const char *name);

/* Load @p name and start its main(); -EBUSY once an app is loaded. */
int multiapp_start(const char *name);

/*
 * The per-extension path, for what loads or unloads one module into a running app (the kernel swap
 * of doc/apps/multiapp-internals.md). A module is loaded with the modules it REQUIRES, its
 * constructors and its multiapp_module_up(), and unloaded with its multiapp_module_down(), its
 * destructors, a sweep of the threads it left in its regions, its shell roots and its regions,
 * after the use count says nothing else imports from it.
 *
 * Both are for the shell's thread (they take the loader's data). Loading an extension that is
 * loaded returns 0. Unloading returns -EBUSY when another extension imports from it or its down
 * hook refuses, -ENOENT when it is not loaded; then it is as it was, apart from what its down
 * hook had stopped.
 */
int multiapp_module_load(const char *name);
int multiapp_module_unload(const char *name);

/* USB has started: the main() of an app that wanted that runs now. */
void multiapp_usb_up(void);

/*
 * Start @p name now, or (returns 1) reboot into it: when an app is loaded or
 * USB runs another profile.
 */
int multiapp_request(const char *name);

/* At boot: start the app a request or CONFIG_MULTIAPP_AUTOSTART names; true if one runs. */
bool multiapp_boot(void);

/* A global function of the loaded app, by name (its hooks), or NULL. */
void *multiapp_app_fn(const char *name);

/* What an app's app_usb_init() calls: nothing to do (include/multiapp/ext.h). */
int multiapp_ext_usb_init(void);

/* What an extension's device_get_binding() calls (include/multiapp/ext.h). */
const struct device *multiapp_device_get_binding(const char *name);

/* Measure main()'s stack use as it returns, for "multiapp info". */
void multiapp_note_main_stack(void);

/*
 * The apps as files on the FAT volume (drive.c). Only at boot, before USB
 * starts and before an app runs (its buffers are in bank 0).
 */
/* Mount, look up and check every built-in app's file, unmount; 0 or -errno (no volume). */
int multiapp_drive_scan(void);
/* The scan's result: 0, or why there is no volume. */
int multiapp_drive_status(void);
/* What the scan found for @p name: its size (or -errno) and whether it equals the built-in one. */
int multiapp_drive_file(const char *name, ssize_t *size, bool *same);
/* Hand the volume to the PC over USB (a boot without an app): ready the disk. */
int multiapp_drive_export(void);
/* Mount the volume read-write for the boot's app, its files read through it: 0 or -errno. */
int multiapp_drive_mount_rw(void);

/* The USB drives go through the disks the boot's app registers (src/drive.c). */
void multiapp_drive_app_disks(void);
/* Read @p name's file into @p buf: its size, or -errno. */
ssize_t multiapp_drive_read(const char *name, uint8_t *buf, size_t max);

#endif /* MULTIAPP_APPS_H_ */
