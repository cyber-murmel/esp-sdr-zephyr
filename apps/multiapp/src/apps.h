#ifndef MULTIAPP_APPS_H_
#define MULTIAPP_APPS_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <sys/types.h>

#include <zephyr/device.h>

/* Where an extension's code and data go; its symbol tables stay in PSRAM. */
enum multiapp_place {
	MULTIAPP_PLACE_PSRAM,
	/* Its IRAM_ATTR code, data and bss below bank 0, the rest in PSRAM (ext/module_fast.ld). */
	MULTIAPP_PLACE_INTERNAL,
	/* As MULTIAPP_PLACE_INTERNAL, its bss in the high region. */
	MULTIAPP_PLACE_INTERNAL_HIGH_BSS,
};

/* An extension built with this image (embedded.c, generated by CMakeLists.txt). */
struct multiapp_embedded {
	const char *name;
	/* Its file (the ELF and its trailer), NULL without CONFIG_MULTIAPP_EMBEDDED. */
	const uint8_t *elf;
	size_t size;
	/* MULTIAPP_USB_*: the USB classes it needs. */
	uint32_t usb;
	/* Whether it has buffers in multiapp_area, which it then owns for the boot. */
	bool area;
	/* A module: code other extensions call, loaded before them, no main(). */
	bool module;
	/* Where its code and data go. */
	enum multiapp_place place;
	/* A module with devices: the host runs its init table as it loads it. */
	bool devices;
	/* It takes the CDC-ACM port from the shell, and its main() starts with USB up. */
	bool console;
	/* SRAM dump bank 2 is the boot's second module heap, and the SDR leaves it alone. */
	bool bank2;
	/* The modules to load before it, NULL-terminated. */
	const char *const *requires;
};

extern const struct multiapp_embedded multiapp_embedded[];
extern const size_t multiapp_embedded_count;

const struct multiapp_embedded *multiapp_embedded_find(const char *name);

/* Load @p name and start its main(); -EBUSY once an app is loaded. */
int multiapp_start(const char *name);

/*
 * The per-extension path, for what loads or unloads one module into a running app (the kernel swap
 * of doc/apps/multiapp-internals.md). A module is loaded with the modules it REQUIRES, its
 * constructors and its multiapp_module_up(), and unloaded with its multiapp_module_down(), its
 * destructors, a sweep of the threads it left in its regions, its shell roots and its regions,
 * after the use count says nothing else imports from it.
 *
 * Both are for the shell's thread (they take the loader's data). Loading an extension that is
 * loaded returns 0. Unloading returns -EBUSY when another extension imports from it or its down
 * hook refuses, -ENOENT when it is not loaded; then it is as it was, apart from what its down
 * hook had stopped.
 */
int multiapp_module_load(const char *name);
int multiapp_module_unload(const char *name);

#if defined(CONFIG_MULTIAPP_STAGES)
/*
 * Hot-swapping a stage (doc/apps/multiapp-internals.md): src/stage.c keeps the stages the running
 * app registered and decides, this file loads and unloads the kernel's extension.
 */
struct llext;
struct multiapp_kernel_desc;

/* A kernel loaded into the running app. */
struct multiapp_kernel {
	/* The extension; NULL when none is loaded. */
	struct llext *ext;
	/* Its llext name, one per load: "ksw<n>". */
	char name[16];
	const struct multiapp_kernel_desc *desc;
	/* The function, where it runs. */
	void *fn;
	enum multiapp_place place;
	/* "upload" or "file". */
	const char *source;
	size_t file_size;
	/* Where its regions execute or live, and how big they are. */
	void *text, *fast, *data, *bss;
	size_t text_size, fast_size, data_size, bss_size, rodata_size, alloc_size;
	/* Its constructors have run. */
	bool up;
};

/*
 * Load a kernel file (the ELF and its trailer) into the running app, check its trailer, build id
 * and dependencies and find its descriptor. 0 or -errno; the shell's thread only.
 */
int multiapp_kernel_load(const uint8_t *file, size_t len, const char *source,
			 struct multiapp_kernel *k);
/* Unload it: -EBUSY if something imports from it. */
int multiapp_kernel_unload(struct multiapp_kernel *k);

/* Back to the defaults and unload every kernel (the app has ended and is about to unload). */
int multiapp_stage_drop_kernels(void);
/* Whether any stage has a kernel loaded. */
bool multiapp_stage_has_kernels(void);
/* Forget the stages whose object @p in says is inside the extension that unloads. */
void multiapp_stage_forget(bool (*in)(const void *obj, void *ctx), void *ctx);

/* The result of a swap, for the shell to print. */
struct multiapp_stage_result {
	/* Request to installation, in us, and whether the stage was idle (installed at once). */
	uint32_t latency_us;
	bool immediate;
	/* The kernel now installed (ext NULL after a revert), and the one it replaced. */
	struct multiapp_kernel kernel;
	bool replaced;
	bool reverted;
	/* What unloading the kernel that was replaced or reverted returned (0, or it stays loaded). */
	int old_ret;
	/* The stage's name, copied. */
	char stage[24];
};

/* The stages: a snapshot of one for "multiapp stage list". */
struct multiapp_stage_view {
	char name[24];
	const char *sig_text;
	uint32_t sig;
	void *dflt, *cur;
	uint32_t abi;
	bool idle;
	bool shared;
	bool pending;
	uint32_t swaps;
	bool has_kernel;
	struct multiapp_kernel kernel;
};
size_t multiapp_stage_count(void);
bool multiapp_stage_view(size_t i, struct multiapp_stage_view *v);

/*
 * Load @p file as a kernel for @p stage and swap it in: wait @p timeout_ms for the app's sync point
 * and unload the kernel it replaces. -ENOENT (no such stage), -ENOEXEC (not for this stage), -ETIMEDOUT
 * (the app never reached its sync point: nothing changed), or what the loader says.
 */
int multiapp_stage_install(const char *stage, const uint8_t *file, size_t len, const char *source,
			   uint32_t timeout_ms, struct multiapp_stage_result *res);
/* Swap back to the app's own function and unload the kernel. */
int multiapp_stage_revert(const char *stage, uint32_t timeout_ms, struct multiapp_stage_result *res);
#else
static inline int multiapp_stage_drop_kernels(void)
{
	return 0;
}

static inline bool multiapp_stage_has_kernels(void)
{
	return false;
}
#endif /* CONFIG_MULTIAPP_STAGES */

/* USB has started: the main() of an app that wanted that runs now. */
void multiapp_usb_up(void);

/*
 * Start @p name now, or (returns 1) reboot into it: when an app is loaded or
 * USB runs another profile.
 */
int multiapp_request(const char *name);

/* At boot: start the app a request or CONFIG_MULTIAPP_AUTOSTART names; true if one runs. */
bool multiapp_boot(void);

/* A global function of the loaded app, by name (its hooks), or NULL; NULL once it is unloading. */
void *multiapp_app_fn(const char *name);

/*
 * The app is unloading (multiapp_app_fn() finds nothing now): forget the handlers src/osmosdr.c
 * found in it and wait for the USB thread to leave the ones it is in. 0, or -EBUSY if one does not
 * return (the app's memory must stay then).
 */
int multiapp_osmosdr_drop(void);

/* What an app's app_usb_init() calls: nothing to do (include/multiapp/ext.h). */
int multiapp_ext_usb_init(void);

/* What an extension's device_get_binding() calls (include/multiapp/ext.h). */
const struct device *multiapp_device_get_binding(const char *name);

/* Measure main()'s stack use as it returns, for "multiapp info". */
void multiapp_note_main_stack(void);

/*
 * The apps as files on the FAT volume (drive.c). Only at boot, before USB
 * starts and before an app runs (its buffers are in bank 0).
 */
/* Mount, look up and check every built-in app's file, unmount; 0 or -errno (no volume). */
int multiapp_drive_scan(void);
/* The scan's result: 0, or why there is no volume. */
int multiapp_drive_status(void);
/* What the scan found for @p name: its size (or -errno) and whether it equals the built-in one. */
int multiapp_drive_file(const char *name, ssize_t *size, bool *same);
/* Hand the volume to the PC over USB (a boot without an app): ready the disk. */
int multiapp_drive_export(void);
/*
 * Whether the PC holds the volume as a USB drive: multiapp_drive_write_begin() refuses then.
 * multiapp_drive_export() sets it; the boots that run an app while MSC is registered will set and
 * clear it as the PC takes the medium and gives it back.
 */
void multiapp_drive_msc_set(bool exported);
/* Mount the volume read-write for the boot's app, its files read through it: 0 or -errno. */
int multiapp_drive_mount_rw(void);

/* The USB drives go through the disks the boot's app registers (src/drive.c). */
void multiapp_drive_app_disks(void);
/* Read @p name's file into @p buf: its size, or -errno. */
ssize_t multiapp_drive_read(const char *name, uint8_t *buf, size_t max);
/*
 * Read the file @p file of the volume's root (a hot-swap kernel, src/stage.c): its size or -errno;
 * -ENOTSUP on the ESP32-S3, whose FATFS object is in ring bank 0, which an app's ring overwrites,
 * and -EBUSY while the PC holds the volume as a USB drive (multiapp_drive_write_begin()'s rule).
 * The caller's thread must have its stack in internal RAM: the flash driver turns the cache off.
 */
ssize_t multiapp_drive_read_file(const char *file, uint8_t *buf, size_t max);

#endif /* MULTIAPP_APPS_H_ */
