"""Give a multiapp extension the Kconfig values it needs and the host lacks.

An extension compiles against the host's autoconf.h. A second Kconfig pass, on the host's fragments
with the extension's on top, says what the extension's own code expects. This writes the difference
between the two as #undef and #define lines, which the extension includes after autoconf.h.

A symbol that differs must be the extension's own (--own) or not apply to what it builds (--drop).
Anything else could change what host and extension agree on, such as the layout of a kernel struct,
so it fails the build: the host has to set it too.
"""

import argparse
import re
import sys

ASSIGN = re.compile(r"^CONFIG_(\w+)=(.*)$")


def parse(path):
    """The symbols a .config sets; one that is "not set" is absent."""
    values = {}
    with open(path) as f:
        for line in f:
            if m := ASSIGN.match(line.strip()):
                values[m.group(1)] = m.group(2)
    return values


def differences(host, ext):
    """(symbol, value in the extension or None), for each symbol the two disagree on."""
    return [(sym, ext.get(sym)) for sym in sorted(set(host) | set(ext)) if host.get(sym) != ext.get(sym)]


def matches(sym, patterns):
    return any(re.fullmatch(p, sym) for p in patterns)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--host", required=True, help="the host's .config")
    p.add_argument("--ext", required=True, help="the .config of the second pass")
    p.add_argument("--own", action="append", default=[], help="regex: symbols of the extension")
    p.add_argument("--drop", action="append", default=[],
                   help="regex: symbols that do not apply to what it builds, left out")
    p.add_argument("--out", required=True, help="the header to write")
    a = p.parse_args()

    host = parse(a.host)
    lines = ["/* Generated by apps/multiapp/extconfig.py. */\n"]
    foreign = []
    for sym, value in differences(host, parse(a.ext)):
        if matches(sym, a.drop):
            continue
        if not matches(sym, a.own):
            foreign.append(f"  CONFIG_{sym}: host {host.get(sym, 'not set')}, "
                           f"extension {'not set' if value is None else value}")
            continue
        lines.append(f"#undef CONFIG_{sym}\n")
        if value is not None:
            lines.append(f"#define CONFIG_{sym} {'1' if value == 'y' else value}\n")
    if foreign:
        sys.exit(f"extconfig.py: {a.ext}: differs from the host; set these in the host too, or "
                 "mark them as the extension's own:\n" + "\n".join(foreign))
    with open(a.out, "w") as f:
        f.writelines(lines)
    return 0


if __name__ == "__main__":
    sys.exit(main())
