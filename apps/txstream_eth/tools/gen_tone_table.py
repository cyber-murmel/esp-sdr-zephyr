"""The test tone's tables for src/tx_tone_gen.h: k = 18 cycles per 351 samples, 8+8 bit samples of
amplitude 1 and DAC words of amplitude 4 counts, as integers, so that the board (soft float libm) and the
host (glibc) cannot round differently.

At 14 of the 351 samples the cosine or the sine is exactly +-0.5 (angles of 60 degrees), where the
rounding of a computed value depends on the last bit of the library: the table rounds those away from zero.

    gen_tone_table.py            print the tables (paste them into tx_tone_gen.h)
    gen_tone_table.py --check    compare them with tx_tone_gen.h (exit 1 if they differ)
"""
import math
import re
import sys
from pathlib import Path

N, K, AMP, AMP8 = 351, 18, 4, 1


def rnd(x):
    """Round half away from zero; a value within 1e-9 of a half counts as the half."""
    if abs(abs(x) - math.floor(abs(x)) - 0.5) < 1e-9:
        return int(math.copysign(math.floor(abs(x)) + 1, x))
    return int(math.floor(x + 0.5))


def tables():
    i8, q8, w = [], [], []
    for i in range(N):
        a = 2 * math.pi * K * i / N
        c, s = math.cos(a), math.sin(a)
        i8.append(rnd(AMP8 * c))
        q8.append(rnd(AMP8 * s))
        wi, wq = max(-511, min(511, rnd(AMP * c))), max(-511, min(511, rnd(AMP * s)))
        w.append((wi & 0x3FF) | ((wq & 0x3FF) << 10))
    return i8, q8, w


def fmt(name, ctype, vals, per, f):
    out = [f"static const {ctype} {name}[TXTG_PERIOD] = {{"]
    for k in range(0, len(vals), per):
        out.append("\t" + ", ".join(f(v) for v in vals[k:k + per]) + ",")
    out.append("};")
    return "\n".join(out)


def text():
    i8, q8, w = tables()
    return "\n".join([
        "/* generated by tools/gen_tone_table.py: do not edit */",
        fmt("txtg_i8", "int8_t", i8, 24, lambda v: f"{v}"),
        fmt("txtg_q8", "int8_t", q8, 24, lambda v: f"{v}"),
        fmt("txtg_w", "uint32_t", w, 8, lambda v: f"0x{v:05x}U"),
    ]) + "\n"


if __name__ == "__main__":
    if "--check" in sys.argv:
        hdr = Path(__file__).resolve().parent.parent / "src" / "tx_tone_gen.h"
        body = hdr.read_text()
        want = text()
        if want not in body:
            print("tx_tone_gen.h differs from the generator", file=sys.stderr)
            sys.exit(1)
        print("tx_tone_gen.h matches")
    else:
        sys.stdout.write(text())
