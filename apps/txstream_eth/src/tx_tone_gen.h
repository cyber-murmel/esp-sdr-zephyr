/**
 * idx mod 351 for a 64 bit index, with 32 bit arithmetic (no 64 bit division on the board): 2^32 mod 351 is 22,
 * so idx = hi x 2^32 + lo is (hi mod 351) x 22 + lo mod 351.
 */
static inline uint32_t txtg_mod(uint64_t idx)
{
	const uint32_t hi = (uint32_t)(idx >> 32), lo = (uint32_t)idx;

	return (((hi % TXTG_PERIOD) * 22U) + (lo % TXTG_PERIOD)) % TXTG_PERIOD;
}

/** The iq8 bytes (I, Q) of sample idx. */
static inline void txtg_iq8(uint64_t idx, int8_t *i8, int8_t *q8)
{
	const uint32_t i = txtg_mod(idx);

	*i8 = txtg_i8[i];
	*q8 = txtg_q8[i];
}

/** The DAC word of sample idx in the word32 format. */
static inline uint32_t txtg_word(uint64_t idx)
{
	return txtg_w[txtg_mod(idx)];
}

