"""Writes the index of the bundled apps: the metadata.json of every eggs/<app>/ as a Python
module, eggs/__init__.py with INDEX = {app: metadata}. It is frozen with the apps, whose
files cannot carry the JSON, so that the launcher lists them without importing them (an app
runs when imported). mpy_port.cmake runs this at configure time; the file is rewritten only
when the index changes.

usage: eggs_index.py [--only APP[,APP...]] EGGS_DIR OUT_FILE

--only lists those apps alone (a board whose manifest freezes some of them, CONFIG_APP_EGGS).
"""

import json
import os
import re
import sys

# metadata.json: the hatchery's fields, all optional; "hidden" keeps an app out of the menu.
TYPES = {"name": str, "description": str, "category": str, "author": str, "revision": int,
         "hidden": bool}


def index(eggs, only=None):
    out = {}
    for app in sorted(os.listdir(eggs)):
        if only is not None and app not in only:
            continue
        folder = os.path.join(eggs, app)
        if not os.path.isdir(folder):
            continue
        if not re.fullmatch(r"[a-z_][a-z0-9_]*", app):
            sys.exit("{}: an app's folder is a module name: lower-case letters, digits and _"
                     .format(folder))
        if not os.path.isfile(os.path.join(folder, "__init__.py")):
            sys.exit("{}: no __init__.py".format(folder))
        path = os.path.join(folder, "metadata.json")
        try:
            with open(path) as f:
                meta = json.load(f)
        except (OSError, ValueError) as e:
            sys.exit("{}: {}".format(path, e))
        if not isinstance(meta, dict):
            sys.exit("{}: not a JSON object".format(path))
        for key, kind in TYPES.items():
            if key in meta and type(meta[key]) is not kind:
                sys.exit("{}: {} is not a {}".format(path, key, kind.__name__))
        out[app] = meta
    if only is not None and set(only) - set(out):
        sys.exit("{}: no app {}".format(eggs, ", ".join(sorted(set(only) - set(out)))))
    return out


def main():
    args = sys.argv[1:]
    only = None
    if args[:1] == ["--only"]:
        only = [a for a in args[1].split(",") if a]
        args = args[2:]
    eggs, out = args
    lines = ["# Generated by tools/eggs_index.py from eggs/*/metadata.json.", "INDEX = {"]
    lines += ["    {!r}: {!r},".format(app, meta) for app, meta in index(eggs, only).items()]
    lines += ["}", ""]
    text = "\n".join(lines)
    try:
        with open(out) as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
