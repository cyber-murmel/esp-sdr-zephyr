"""Render the radio block diagrams doc/radio/transceiver-<chip>.svg.

One SVG per chip (ESP32-S3, ESP32-C6, ESP32-C5, ESP32-S31, ESP32), drawn like a
textbook transceiver: the antenna and T/R switch on the left, the receive chain
along the top (left to right), the shared LO in the middle, the transmit chain
along the bottom (right to left). Labels are red for receive, blue for
transmit, green for shared parts. Each block has a grey box with the registers
that influence it (name, analog I2C block:reg [bits] or peripheral address
[bits], effect) and, in purple, the esp_sdr call that drives it. Blocks with no
known register are dashed.

What is drawn follows the sources: one front end and one antenna pin (half
duplex), one crystal and one LO for both mixers. The direct conversion (zero
IF) receiver and the I/Q split at the RF mixer are inferred: the first baseband
block already has separate I and Q codes. Register names follow the register
pages generated by doc/registers/svd2md.py, for the other chips the names in
lib/esp_sdr/src/esp_sdr_priv.h.

The tables (one per chip: blocks, wires, register boxes; the parts all chips
share first) come first, the drawing primitives after, then main(). Text stays
SVG <text> (sans-serif and monospace, no embedded fonts), so register names stay
searchable; the output is deterministic.

Run: python3 doc/radio/transceiver.py writes the SVGs next to this file.
--check: exit 1 if a committed SVG differs from what the script would write.
"""

