def num(v):
    v = round(v, 1)
    return str(int(v)) if v == int(v) else f"{v:.1f}"


def pts(points):
    return " ".join(f"{num(x)},{num(y)}" for x, y in points)


class Canvas:
    def __init__(self, width, height):
        self.width, self.height = width, height
        self.out = []

    def add(self, s):
        self.out.append(s)

    def text(self, x, y, s, size=LABEL_SIZE, fill=INK, anchor="middle", mono=False,
             weight=None, italic=False):
        attrs = [f'x="{num(x)}"', f'y="{num(y)}"', f'font-size="{size}"']
        if mono:
            attrs.append('font-family="monospace"')
        if anchor != "start":
            attrs.append(f'text-anchor="{anchor}"')
        if fill != INK:
            attrs.append(f'fill="{fill}"')
        if weight:
            attrs.append(f'font-weight="{weight}"')
        if italic:
            attrs.append('font-style="italic"')
        self.add(f'<text {" ".join(attrs)}>{escape(s)}</text>')

    def lines(self, x, y, lines, size, fill, anchor="middle"):
        """Lines centred vertically on y."""
        lh = size + 3
        top = y - (len(lines) - 1) * lh / 2 + size * 0.35
        for i, s in enumerate(lines):
            self.text(x, top + i * lh, s, size, fill, anchor)

    def shape(self, tag, attrs, dashed=False, fill="#ffffff", width=STROKE):
        extra = f' stroke-dasharray="{DASH}"' if dashed else ""
        self.add(f'<{tag} {attrs} fill="{fill}" stroke="{INK}" '
                 f'stroke-width="{num(width)}"{extra}/>')

    def line(self, a, b, width=STROKE, marker=None, color=INK):
        m = f' marker-end="url(#{marker})"' if marker else ""
        self.add(f'<line x1="{num(a[0])}" y1="{num(a[1])}" x2="{num(b[0])}" '
                 f'y2="{num(b[1])}" stroke="{color}" stroke-width="{num(width)}"{m}/>')

    def svg(self, title, desc):
        head = [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.width} '
            f'{self.height}" width="{self.width}" height="{self.height}" '
            f'font-family="sans-serif" role="img">',
            f"<title>{escape(title)}</title>",
            f"<desc>{escape(desc)}</desc>",
            "<defs>",
            '<marker id="arrow" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="9" '
            'markerHeight="9" markerUnits="userSpaceOnUse" orient="auto">'
            '<path d="M0,1 L10,5 L0,9 z" fill="#000000"/></marker>',
            '<marker id="tip" viewBox="0 0 10 10" refX="10" refY="5" markerWidth="7" '
            'markerHeight="7" markerUnits="userSpaceOnUse" orient="auto">'
            '<path d="M0,1 L10,5 L0,9 z" fill="#000000"/></marker>',
            "</defs>",
            f'<rect x="0" y="0" width="{self.width}" height="{self.height}" fill="#ffffff"/>',
        ]
        return "\n".join(head + self.out + ["</svg>"]) + "\n"


def size(b):
    w, h = SIZE[b["kind"]]
    return b.get("w", w), b.get("h", h)


def port(b, name):
    """A block's port: c, l, r, t, b, tr (top right corner) or a named one."""
    x, y = b["at"]
    if name in b.get("ports", {}):
        dx, dy = b["ports"][name]
        return x + dx, y + dy
    w, h = size(b)
    kind, d = b["kind"], b.get("dir", "r")
    if name == "c":
        return x, y
    if kind == "amp" and d in "rl" and name in "tb":
        return x, y + (h / 4 if name == "b" else -h / 4)
    if kind == "amp" and d in "ud" and name in "lr":
        return x + (w / 4 if name == "r" else -w / 4), y
    return {"l": (x - w / 2, y), "r": (x + w / 2, y), "t": (x, y - h / 2),
            "b": (x, y + h / 2), "tr": (x + w / 2 - 6, y - h / 2)}[name]


def resolve(blocks, points):
    out = []
    for p in points:
        if isinstance(p, str):
            bid, _, name = p.partition(".")
            out.append(port(blocks[bid], name or "c"))
        else:
            x, y = p
            out.append((out[-1][0] if x is None else x, out[-1][1] if y is None else y))
    for (x0, y0), (x1, y1) in zip(out, out[1:]):
        if x0 != x1 and y0 != y1:
            raise ValueError(f"wire segment not orthogonal: {points}")
    return out


def wire(cv, points, arrow=True, hops=()):
    """A wire through points; at each hop it jumps another wire in a half circle."""
    d = [f"M{num(points[0][0])},{num(points[0][1])}"]
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        on = []
        for hx, hy in hops:
            if x0 == x1 == hx and min(y0, y1) < hy < max(y0, y1):
                on.append((abs(hy - y0), hx, hy))
            elif y0 == y1 == hy and min(x0, x1) < hx < max(x0, x1):
                on.append((abs(hx - x0), hx, hy))
        for _, hx, hy in sorted(on):
            if x0 == x1:
                s = 1 if y1 > y0 else -1
                d.append(f"L{num(hx)},{num(hy - s * HOP_R)}")
                d.append(f"A{HOP_R},{HOP_R} 0 0 {1 if s > 0 else 0} "
                         f"{num(hx)},{num(hy + s * HOP_R)}")
            else:
                s = 1 if x1 > x0 else -1
                d.append(f"L{num(hx - s * HOP_R)},{num(hy)}")
                d.append(f"A{HOP_R},{HOP_R} 0 0 {1 if s > 0 else 0} "
                         f"{num(hx + s * HOP_R)},{num(hy)}")
        d.append(f"L{num(x1)},{num(y1)}")
    m = ' marker-end="url(#arrow)"' if arrow else ""
    cv.add(f'<path d="{" ".join(d)}" fill="none" stroke="{INK}" '
           f'stroke-width="{STROKE}"{m}/>')


def rect(cv, x, y, w, h, dashed=False):
    cv.shape("rect", f'x="{num(x - w / 2)}" y="{num(y - h / 2)}" width="{num(w)}" '
             f'height="{num(h)}"', dashed)


def wave(cv, x, y, half=11):
    """One period of a sine, centred on (x, y)."""
    cv.add(f'<path d="M{num(x - half)},{num(y)} Q{num(x - half / 2)},{num(y - 9)} '
           f'{num(x)},{num(y)} T{num(x + half)},{num(y)}" fill="none" '
           f'stroke="{INK}" stroke-width="1.1"/>')


def draw_antenna(cv, b):
    x, y = b["at"]
    top = y - 90
    cv.line((x, y), (x, top - 18))
    cv.shape("path", f'd="M{num(x - 11)},{num(top - 18)} L{num(x + 11)},{num(top - 18)} '
             f'L{num(x)},{num(top)} z"', fill="none")


def draw_switch(cv, b):
    x, y = b["at"]
    w, h = size(b)
    rect(cv, x, y, w, h, b.get("dashed", False))
    com, rxc, txc = (x - 16, y), (x + 15, y - 14), (x + 15, y + 14)
    cv.line((x - w / 2, y), com)
    cv.line(rxc, (rxc[0], y - h / 2))
    cv.line(txc, (txc[0], y + h / 2))
    cv.line(com, (rxc[0] - 3, rxc[1] + 1))
    for cx, cy in (com, rxc, txc):
        cv.shape("circle", f'cx="{num(cx)}" cy="{num(cy)}" r="2.6"', width=1.2)
    # The blade moves between the two throws.
    cv.add(f'<path d="M{num(x + 4)},{num(y - 8)} Q{num(x + 12)},{num(y)} '
           f'{num(x + 4)},{num(y + 8)}" fill="none" stroke="{INK}" stroke-width="1" '
           f'marker-end="url(#tip)"/>')


def draw_amp(cv, b):
    x, y = b["at"]
    w, h = size(b)
    tri = {"r": [(x - w / 2, y - h / 2), (x - w / 2, y + h / 2), (x + w / 2, y)],
           "l": [(x + w / 2, y - h / 2), (x + w / 2, y + h / 2), (x - w / 2, y)],
           "u": [(x - w / 2, y + h / 2), (x + w / 2, y + h / 2), (x, y - h / 2)],
           "d": [(x - w / 2, y - h / 2), (x + w / 2, y - h / 2), (x, y + h / 2)]}
    cv.shape("polygon", f'points="{pts(tri[b.get("dir", "r")])}"', b.get("dashed", False))
    if b.get("var"):
        cv.line((x - w * 0.42, y + h * 0.62), (x + w * 0.36, y - h * 0.66), 1.1, "tip")


def draw_mixer(cv, b):
    x, y = b["at"]
    r = size(b)[0] / 2
    cv.shape("circle", f'cx="{num(x)}" cy="{num(y)}" r="{num(r)}"', b.get("dashed", False))
    k = r * 0.707
    cv.line((x - k, y - k), (x + k, y + k), 1.2)
    cv.line((x - k, y + k), (x + k, y - k), 1.2)


def draw_filter(cv, b):
    x, y = b["at"]
    w, h = size(b)
    rect(cv, x, y, w, h, b.get("dashed", False))
    for i, dy in enumerate((-9, 0, 9)):
        wave(cv, x, y + dy + 2)
        if b.get("lp") and i < 2:  # low-pass: the upper (high) bands struck out
            cv.line((x - 4, y + dy + 6), (x + 4, y + dy - 2), 1.1)


