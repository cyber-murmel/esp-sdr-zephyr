def label(cv, b):
    if not b.get("label"):
        return
    x, y = b["at"]
    w, h = size(b)
    lines = b["label"].split("\n")
    lh = LABEL_SIZE + 3
    where = b.get("lab", "above")
    if where == "above":
        x0, y0, anchor = x, y - h / 2 - 7 - (len(lines) - 1) * lh, "middle"
    elif where == "below":
        x0, y0, anchor = x, y + h / 2 + LABEL_SIZE + 3, "middle"
    elif where == "left":
        x0, y0, anchor = x - w / 2 - 6, y + 4 - (len(lines) - 1) * lh / 2, "end"
    elif where == "right":
        x0, y0, anchor = x + w / 2 + 6, y + 4 - (len(lines) - 1) * lh / 2, "start"
    else:
        dx, dy, anchor = where
        x0, y0 = x + dx, y + dy
    for i, s in enumerate(lines):
        cv.text(x0, y0 + i * lh, s, LABEL_SIZE, COLOR[b["path"]], anchor)


def box_size(lines, api=None):
    n = len(lines) + (1 if api else 0)
    width = max(len(s) for s in lines + ([api] if api else [])) * MONO_W + 2 * PAD
    return width, n * LINE_H + 2 * PAD - 3


def text_box(cv, x, y, lines, api=None):
    """A grey register box with its top left corner at (x, y)."""
    w, h = box_size(lines, api)
    cv.add(f'<rect x="{num(x)}" y="{num(y)}" width="{num(w)}" height="{num(h)}" rx="3" '
           f'fill="{REG_FILL}" stroke="{REG_STROKE}" stroke-width="1"/>')
    rows = [(s, REG_INK) for s in lines] + ([(api, API)] if api else [])
    for i, (s, fill) in enumerate(rows):
        cv.text(x + PAD, y + PAD + 8 + i * LINE_H, s, MONO_SIZE, fill, "start", mono=True)


def leader(cv, box, target):
    """Dotted line from the nearest point of the box (x, y, w, h) to the target."""
    x, y, w, h = box
    tx, ty = target
    sx, sy = min(max(tx, x), x + w), min(max(ty, y), y + h)
    cv.add(f'<line x1="{num(sx)}" y1="{num(sy)}" x2="{num(tx)}" y2="{num(ty)}" '
           f'stroke="{LEADER}" stroke-width="1.3" stroke-dasharray="0.1 3.2" '
           f'stroke-linecap="round"/>')
    cv.add(f'<circle cx="{num(tx)}" cy="{num(ty)}" r="2.2" fill="{LEADER}"/>')


def legend(cv, x, y):
    cv.text(x, y, "receive", 12, COLOR[RX], "start")
