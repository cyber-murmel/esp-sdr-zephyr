# Blocks: id, kind, centre, path (colour), label. Options: dashed (no register
# known), lab (label place: above, below, left, right or (dx, dy, anchor)),
# text (text inside), dir (amplifier points r, l, u or d), var (variable gain
# arrow), lp (low-pass waves), w and h (size), ports (named ports as offsets).
# Wires: points "block.port" (c, l, r, t, b or a named port), (x, y), or
# (x, None) / (None, y) to keep the other coordinate of the previous point;
# hops are crossings with another wire.
# Texts: x, y, text, path or "note", anchor.
# Regs: the block and port the leader points at, the box's top left corner,
# the register lines and the esp_sdr call.


def tweak(blocks, **changes):
    """Copies of blocks with options changed by id, as tweak(FRONT, adci={"dashed": True})."""
    return [dict(b, **changes.get(b["id"], {})) for b in blocks]


